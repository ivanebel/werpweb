function normalizeLocale(value) {
  if (!value) return null;
  const raw = String(value).trim().replace('_', '-').toLowerCase();
  if (!raw) return null;
  for (const locale of LOCALES) {
    if (raw === locale.code.toLowerCase()) return locale.code;
  }
  if (raw === 'es' || raw.startsWith('es-')) return 'es-AR';
  if (raw === 'en' || raw.startsWith('en-')) return 'en-US';
  return null;
}

function parseCookies(header) {
  const cookies = {};
  if (!header) return cookies;
  for (const part of String(header).split(';')) {
    const index = part.indexOf('=');
    if (index < 0) continue;
    const key = part.slice(0, index).trim();
    const value = part.slice(index + 1).trim();
    if (!key) continue;
    try {
      cookies[key] = decodeURIComponent(value);
    } catch {
      cookies[key] = value;
    }
  }
  return cookies;
}

function getRequestLocale(req) {
  const sessionLocale = req.session && normalizeLocale(req.session.locale);
  if (sessionLocale) return sessionLocale;
  const cookieLocale = normalizeLocale(parseCookies(req.headers.cookie)[LOCALE_COOKIE]);
  if (cookieLocale) return cookieLocale;
  return DEFAULT_LOCALE;
}

function interpolate(template, params) {
  if (!params) return template;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name) => {
    if (params[name] === undefined || params[name] === null) return match;
    return String(params[name]);
  });
}

function translate(locale, key, params) {
  if (key === null || key === undefined) return '';
  const source = String(key);
  if (normalizeLocale(locale) === 'es-AR' && Object.prototype.hasOwnProperty.call(ES, source)) {
    return interpolate(ES[source], params);
  }
  return interpolate(source, params);
}

function translator(locale) {
  const normalized = normalizeLocale(locale) || DEFAULT_LOCALE;
  return (key, params) => translate(normalized, key, params);
}

function localeLabel(code) {
  const locale = LOCALES.find((item) => item.code === normalizeLocale(code));
  return locale ? locale.label : DEFAULT_LOCALE;
}

function decodeHtmlText(value) {
  return String(value)
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/&#39;|&apos;/g, "'")
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&nbsp;/g, ' ');
}

function escapeHtml(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

function translateTextNode(text, t) {
  const match = String(text).match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!match) return text;
  const leading = match[1];
  const body = match[2];
  const trailing = match[3];
  if (!body.trim()) return text;
  const key = decodeHtmlText(body).replace(/\s+/g, ' ').trim();
  if (!key || !Object.prototype.hasOwnProperty.call(ES, key)) return text;
  return `${leading}${t(key)}${trailing}`;
}

function localizeHtml(html, locale) {
  if (!html || normalizeLocale(locale) !== 'es-AR') return html;
  const t = translator(locale);
  let output = '';
  let last = 0;
  const scriptPattern = /<(script|style)\b[^>]*>[\s\S]*?<\/\1>/gi;
  let scriptMatch;
  while ((scriptMatch = scriptPattern.exec(html)) !== null) {
    output += localizeHtmlSegment(html.slice(last, scriptMatch.index), t);
    output += scriptMatch[0];
    last = scriptMatch.index + scriptMatch[0].length;
  }
  output += localizeHtmlSegment(html.slice(last), t);
  return output;
}

function localizeHtmlSegment(segment, t) {
  let result = segment.replace(/>([^<]+)</g, (match, text) => `>${translateTextNode(text, t)}<`);
  result = result.replace(/\b(placeholder|aria-label|title|data-confirm|alt)="([^"]*)"/g, (match, name, value) => {
    const key = decodeHtmlText(value).replace(/\s+/g, ' ').trim();
    if (!key || !Object.prototype.hasOwnProperty.call(ES, key)) return match;
    return `${name}="${escapeHtml(t(key))}"`;
  });
  return result;
}

